# ── Helpers ────────────────────────────────────────────────────────────────────

def e(s) -> str:
    return html_lib.escape(str(s))

def render_en(content) -> str:
    if isinstance(content, str):
        return f"<p>{e(content)}</p>"
    parts = []
    for item in content:
        if isinstance(item, str):
            parts.append(e(item))
        elif isinstance(item, dict):
            t = item.get("type", "concept")
            parts.append(f'<mark class="hl hl-{t}">{e(item.get("text",""))}</mark>')
    return "<p>" + "".join(parts) + "</p>"

