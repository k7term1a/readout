def load_table(blk: dict, base_dir: Path) -> dict | None:
    """Load table from tables/<table_id>.json. Returns None if file missing."""
    tid = blk.get("table_id", "")
    if not tid:
        return None
    tbl_path = base_dir / "tables" / f"{tid}.json"
    if tbl_path.exists():
        with open(tbl_path, encoding="utf-8") as f:
            return json.load(f)
    return None

def render_table_html(tbl: dict, referenced_rows: set) -> str:
    tid     = tbl["id"]
    headers = tbl.get("headers", [])
    rows    = tbl.get("rows", [])
    th_html = "".join(f"<th>{e(h)}</th>" for h in headers)
    tr_html = ""
    for i, row in enumerate(rows):
        cls = ' class="row-ref"' if i in referenced_rows else ""
        tds = "".join(f"<td>{e(c)}</td>" for c in row)
